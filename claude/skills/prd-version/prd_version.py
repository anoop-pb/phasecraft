#!/usr/bin/env python3
"""prd-version: PRD summary and change-note completeness check.

Subcommands:
  summary --version X.Y[.Z] [--root DIR]
      Reads {prd}/sections/, writes {prd}/SUMMARY.md (version, feature index,
      cross-feature interactions, NFR lines).
  check --to X.Y[.Z] [--from A] [--root DIR]
      Compares the section files changed since git tag prd-v{A} with the
      section files listed in {prd}/changes/CHANGES-v{X.Y[.Z]}.md, checks
      that every row's Type is new, changed, or clarified, and that the
      version step matches the highest row type (new: major, changed: minor,
      clarified only: patch). Exits 1 on any mismatch. Without --from (first
      version), checks only the note's existence and row types.

{prd} is the PRD root: the `PRD root` row of REPO-MAP.md at the repo root,
or prd/ when REPO-MAP.md or the row is absent.

X.Y and X.Y.0 name the same version; either form finds the tag and the note.
"""
import argparse
import datetime
import re
import subprocess
import sys
from pathlib import Path

FEATURE_RE = re.compile(r"^(\d+)-(.+?)(-tests)?\.md$")
PRD_ROOT_ROW = re.compile(r"^\|\s*PRD root\s*\|\s*`([^`]+)`\s*\|", re.I)


def die(msg, code=2):
    print(f"prd-version: {msg}", file=sys.stderr)
    sys.exit(code)


def read(p: Path) -> str:
    return p.read_text(encoding="utf-8")


def prd_root(root: Path) -> Path:
    """PRD root relative to the repo root, from REPO-MAP.md; default prd/."""
    repo_map = root / "REPO-MAP.md"
    if repo_map.exists():
        for ln in read(repo_map).splitlines():
            m = PRD_ROOT_ROW.match(ln.strip())
            if m:
                rel = m.group(1).strip().strip("/")
                if not rel or ".." in Path(rel).parts:
                    die(f"REPO-MAP.md: unusable PRD root '{m.group(1)}'")
                return Path(rel)
    return Path("prd")


def feature_specs(fr_dir: Path):
    """Sorted [(number, name, spec_path)], test files excluded."""
    out = []
    for p in sorted(fr_dir.glob("*.md")):
        m = FEATURE_RE.match(p.name)
        if m and not m.group(3):
            out.append((m.group(1), m.group(2), p))
    return out


def section_body(text: str, heading: str) -> str:
    """Body of the first heading matching `heading` (any level), up to the next heading."""
    m = re.search(rf"^#{{1,6}}\s+{re.escape(heading)}\b.*$", text, re.M | re.I)
    if not m:
        return ""
    rest = text[m.end():]
    n = re.search(r"^#{1,6}\s+", rest, re.M)
    return (rest[: n.start()] if n else rest).strip()


def first_description_line(text: str) -> str:
    for ln in section_body(text, "Description").splitlines():
        s = ln.strip()
        if s:
            return s.lstrip("-* ").strip()
    return ""


def dep_numbers(text: str):
    """Feature numbers named in Dependencies, as ints, so "1" matches "01"."""
    body = section_body(text, "Dependencies")
    return sorted({int(d) for d in re.findall(r"\b(\d{1,3})\b", body)})


def nfr_flag(text: str) -> str:
    body = section_body(text, "NFR implications")
    cleaned = re.sub(r"[-*\s.]", "", body.lower())
    return "no" if cleaned in ("", "none", "—", "n/a", "na") else "yes"


def cmd_summary(args):
    root = Path(args.root).resolve()
    prd = prd_root(root)
    sections = root / prd / "sections"
    if not sections.is_dir():
        die(f"{sections} not found")
    fr_dir = sections / "03-functional-requirements"
    feats = feature_specs(fr_dir) if fr_dir.is_dir() else []
    by_int = {int(num): (num, name) for num, name, _ in feats}

    idx = ["| # | Feature | Description | Depends on | Depended on by | NFR |",
           "|---|---------|-------------|------------|----------------|-----|"]
    deps_of = {}
    for num, name, spec in feats:
        deps_of[num] = [by_int[d][0] for d in dep_numbers(read(spec))
                        if d in by_int and d != int(num)]
    rdeps = {num: [n for n, ds in deps_of.items() if num in ds] for num, _, _ in feats}
    inter = []
    for num, name, spec in feats:
        t = read(spec)
        idx.append(f"| {num} | {name} | {first_description_line(t)} | "
                   f"{', '.join(deps_of[num]) or '—'} | {', '.join(rdeps[num]) or '—'} | "
                   f"{nfr_flag(t)} |")
        for d in deps_of[num]:
            inter.append(f"- {num} {name} depends on {d} {by_int[int(d)][1]}")

    nfr_lines = []
    nfr_file = sections / "04-non-functional-requirements.md"
    if nfr_file.exists():
        for ln in read(nfr_file).splitlines():
            if ln.lstrip().startswith(("-", "*")):
                nfr_lines.append("- " + ln.lstrip("-* ").strip())

    out = root / prd / "SUMMARY.md"
    out.write_text("\n".join(
        [f"# PRD summary", "", f"Version: v{args.version}",
         f"Date: {datetime.date.today().isoformat()}",
         "Generated by prd-version. Do not edit.", "",
         "## Feature index", ""] + idx +
        ["", "## Cross-feature interactions", ""] + (inter or ["- none"]) +
        ["", "## NFR", ""] + (nfr_lines or ["- none"])) + "\n", encoding="utf-8")
    print(out)


def version_forms(v: str) -> list:
    """The given form first, then its equivalent: X.Y <-> X.Y.0."""
    parts = v.split(".")
    if len(parts) == 2:
        return [v, v + ".0"]
    if len(parts) == 3 and parts[2] == "0":
        return [v, ".".join(parts[:2])]
    return [v]


def find_tag(root: Path, v: str) -> str:
    for form in version_forms(v):
        tag = f"prd-v{form}"
        r = subprocess.run(["git", "-C", str(root), "rev-parse", "-q", "--verify",
                            f"refs/tags/{tag}"], capture_output=True, text=True)
        if r.returncode == 0:
            return tag
    die(f"no git tag prd-v{v}")


def git(root: Path, *argv) -> list:
    r = subprocess.run(["git", "-C", str(root), *argv], capture_output=True, text=True)
    if r.returncode != 0:
        die(f"git {' '.join(argv)} failed: {r.stderr.strip()}")
    return [ln.strip() for ln in r.stdout.splitlines() if ln.strip()]


TYPES = {"clarified": 0, "changed": 1, "new": 2}
BUMPS = ["patch", "minor", "major"]


def note_rows(note: Path):
    """[(section file, type)] from the change note's table."""
    rows, type_col = [], None
    for ln in read(note).splitlines():
        cells = [c.strip().strip("`") for c in ln.strip().strip("|").split("|")]
        if len(cells) < 2:
            continue
        if cells[0].lower() == "section file":
            low = [c.lower() for c in cells]
            type_col = low.index("type") if "type" in low else None
        elif cells[0].endswith(".md"):
            t = cells[type_col].lower() if type_col is not None and type_col < len(cells) else ""
            rows.append((cells[0], t))
    return rows


def parse_version(v: str):
    parts = v.split(".")
    if not 2 <= len(parts) <= 3 or not all(p.isdigit() for p in parts):
        die(f"not a version: {v}")
    nums = [int(p) for p in parts] + [0] * (3 - len(parts))
    return tuple(nums)


def version_step(frm: str, to: str):
    """The bump class from one version to the next, or None if not a single step."""
    a, b = parse_version(frm), parse_version(to)
    if b == (a[0] + 1, 0, 0):
        return "major"
    if b == (a[0], a[1] + 1, 0):
        return "minor"
    if b == (a[0], a[1], a[2] + 1):
        return "patch"
    return None


def cmd_check(args):
    root = Path(args.root).resolve()
    prd = prd_root(root)
    notes = [root / prd / "changes" / f"CHANGES-v{v}.md" for v in version_forms(args.to)]
    note = next((n for n in notes if n.exists()), None)
    if note is None:
        die(f"{notes[0]} not found — the product manager writes it", 1)
    rows = note_rows(note)
    bad = [f for f, t in rows if t not in TYPES]
    for f in bad:
        print(f"row without a valid Type (new | changed | clarified): {f}")
    if bad:
        sys.exit(1)
    if not args.frm:
        print(f"first version: {note.name} exists, {len(rows)} typed row(s); no comparison")
        return
    step = version_step(args.frm, args.to)
    if rows:
        expected = BUMPS[max(TYPES[t] for _, t in rows)]
        if step != expected:
            print(f"version step v{args.frm} -> v{args.to} is {step or 'not a single bump'}; "
                  f"highest row type requires a {expected} bump")
            sys.exit(1)
    prefix = (prd / "sections").as_posix() + "/"
    changed = git(root, "diff", "--name-only", find_tag(root, args.frm), "--", prefix)
    changed += git(root, "ls-files", "--others", "--exclude-standard", "--", prefix)
    changed = {p[len(prefix):] for p in changed if p.startswith(prefix)}
    listed = {f for f, _ in rows}
    missing, extra = sorted(changed - listed), sorted(listed - changed)
    for p in missing:
        print(f"changed but not in change note: {p}")
    for p in extra:
        print(f"in change note but not changed: {p}")
    if missing or extra:
        sys.exit(1)
    print(f"ok: {len(changed)} changed section file(s), all in {note.name}")


def main():
    ap = argparse.ArgumentParser(prog="prd-version")
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("summary")
    s.add_argument("--version", required=True)
    s.add_argument("--root", default=".")
    s.set_defaults(fn=cmd_summary)
    c = sub.add_parser("check")
    c.add_argument("--to", required=True)
    c.add_argument("--from", dest="frm")
    c.add_argument("--root", default=".")
    c.set_defaults(fn=cmd_check)
    args = ap.parse_args()
    args.fn(args)


if __name__ == "__main__":
    main()
